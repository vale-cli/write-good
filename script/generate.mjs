// Generates the rules in ../write-good from the checks write-good ships.
//
//   npm install && node generate.mjs
//
// The version comes from package.json.
import fs from 'node:fs'
import path from 'node:path'
import {fileURLToPath} from 'node:url'
import yaml from 'js-yaml'
import {adverb, cliche, eprime, passive, version, weasel, wordy} from './lists.mjs'

const here = path.dirname(fileURLToPath(import.meta.url))
const out = path.join(here, '..', 'write-good')
const source = `write-good ${version('write-good')}`

// Each entry is a piece of a regular expression, as write-good uses it.
const unique = (list) => [...new Set(list)]

function write(name, rule) {
  const text = yaml.dump(rule, {lineWidth: -1, quotingType: '"'})
  fs.writeFileSync(
    path.join(out, `${name}.yml`),
    `# Generated by script/generate.mjs from ${source}. Do not edit.\n${text}`
  )
}

// A sentence, to write-good, is what sits between two runs of `.;!?` on one
// line, so a line that never reaches one has no sentences.
const START = String.raw`(?<=(?:^|[.;!?])[^\S\n]*)`
const END = String.raw`(?=[^\n.;!?]*[.;!?])`

write('Weasel', {
  extends: 'existence',
  message: "'%s' is a weasel word",
  ignorecase: true,
  level: 'warning',
  // `too many` and `too few` are fine. A phrase is matched with single
  // spaces, as write-good does.
  tokens: weasel.weasels.map((w) =>
    weasel.exceptions.includes(w)
      ? `(?<!(?-i:too) )${w}`
      : w.replace(/ /g, '[ ]')
  )
})

write('Illusions', {
  extends: 'existence',
  message: "'%s' is repeated",
  ignorecase: true,
  nonword: true,
  level: 'warning',
  action: {name: 'remove'},
  // A word, punctuation and all, that repeats the one before it.
  tokens: [String.raw`(?<=(?<!\S)(\S+)\s+)\1(?!\S)(?<=\w\S*)`]
})

write('So', {
  extends: 'existence',
  message: "'%s' adds no meaning",
  ignorecase: true,
  nonword: true,
  level: 'error',
  tokens: [String.raw`${START}so\b(?=[^\n.;!?]+[.;!?])`]
})

write('ThereIs', {
  extends: 'existence',
  message: "'%s' is unnecessary verbiage",
  ignorecase: true,
  nonword: true,
  level: 'error',
  tokens: [String.raw`${START}there[^\S\n](?:is|are)\b${END}`]
})

write('Passive', {
  extends: 'existence',
  message: "'%s' may be passive voice",
  ignorecase: true,
  level: 'warning',
  raw: [String.raw`\b(am|are|were|being|is|been|was|be)\b\s*`],
  tokens: [
    `(?!(?:${passive.exceptions.join('|')})\\b)[\\w]+ed`,
    ...unique(passive.irregulars)
  ]
})

write('Adverbs', {
  extends: 'existence',
  message: "'%s' can weaken meaning",
  ignorecase: true,
  level: 'warning',
  tokens: [...unique(adverb.adverbs).map((a) => `${a}y`), ...adverb.weakens]
})

// write-good allows any whitespace between the words of a phrase, which is
// what Vale does with a space.
write('TooWordy', {
  extends: 'existence',
  message: "'%s' is wordy or unneeded",
  ignorecase: true,
  level: 'warning',
  raw: ['(?<!-)'],
  tokens: unique(wordy.wordyWords)
})

write('Cliches', {
  extends: 'existence',
  message: "'%s' is a cliche",
  ignorecase: true,
  level: 'warning',
  tokens: unique(cliche.cliches)
})

// Off by default in write-good. A curly apostrophe counts as a straight one.
write('E-Prime', {
  extends: 'existence',
  message: "'%s' is a form of 'to be'",
  ignorecase: true,
  level: 'suggestion',
  tokens: unique(eprime.toBe).map((w) => w.replace(/'/g, "['‘’]"))
})

console.log(`wrote the rules from ${source}`)
